import vm from 'node:vm';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const calls=[];
const window={Native:{invoke:(id,method,args)=>calls.push({id,method,args:JSON.parse(args)})}};
vm.runInNewContext(readFileSync('app/src/main/assets/app/bridge.js','utf8'),{window,Map,Set,Promise,Error,JSON,console,document:{querySelector(){return null;}}});
const start=window.cocoa.playback.nativeStart({resumePosition:123.5,resumeDuration:3600,stream:{url:'https://example.org/movie.mp4'}});
assert.equal(calls[0].args[0].resumePosition,123500,'Convert resume seconds to native milliseconds');
window.__nativeResolve(calls[0].id,true,{ok:true});await start;
let stats;
window.cocoa.playback.onNativeStats(value=>stats=value);
window.__nativeEvent('native-stats',{position:123500,duration:3600000,buffered:140000});
assert.equal(stats.position,123.5);assert.equal(stats.duration,3600);
let closed;
window.cocoa.playback.onNativeClosed(value=>closed=value);
window.__nativeEvent('native-closed',{position:123500,duration:3600000,ended:false});
assert.equal(closed.position,123.5,'Persist history in seconds');
window.cocoa.cast.discover();assert.equal(calls.at(-1).method,'cast:discover','Casting cannot return a fake empty success');
window.cocoa.trakt.status();assert.equal(calls.at(-1).method,'trakt:status','Trakt must query actual connection status');
console.log('Bridge: resume, progress, casting and Trakt routing PASS');
